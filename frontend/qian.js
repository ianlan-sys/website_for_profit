const DIGITS = '零一二三四五六七八九';
export function cnNumber(n) {
  if (n === 100) return '一百';
  const tens = Math.floor(n / 10), ones = n % 10;
  if (!tens) return DIGITS[ones];
  return (tens === 1 ? '' : DIGITS[tens]) + '十' + (ones ? DIGITS[ones] : '');
}
// pick(n) must return an integer in [0, n). The server passes crypto.randomInt; the browser passes a crypto-backed picker.
export function composeReading(qian, aspect, pick) {
  const q = qians[qian - 1], guide = aspectGuides[aspect];
  const lens = pick(guide.lens.length), act = pick(guide.actions.length);
  return {
    id: `q${qian}-${aspect}-${lens}${act}`, topic: aspect, qian, level: q.level, number: cnNumber(qian),
    name: q.name, poem: [...q.poem], title: q.title, body: [q.meaning, guide.lens[lens]],
    action: guide.actions[act][0], time: guide.actions[act][1], seal: q.seal
  };
}
